## Vacation Accrual

Full-time employees receive 20 vacation days per calendar year.

## Vacation Carry-Over

Employees may carry over up to 10 unused vacation days into the following calendar year.

Any vacation days above the 10-day carry-over limit expire at the end of the calendar year.

## Vacation Requests

Employees should submit vacation requests through the company HR system at least two weeks before the requested time off whenever practical.

## Policy Authority

This document is retired and must not be used as the current source for vacation carry-over rules.
